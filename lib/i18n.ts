const expenseCategoryKeys: Partial<Record<string, TranslationKey>> = {
  Transport: 'expenseCategory.transport',
  Fuel: 'expenseCategory.fuel',
  Packaging: 'expenseCategory.packaging',
  Telephone: 'expenseCategory.telephone',
  Marketing: 'expenseCategory.marketing',
  Office: 'expenseCategory.office',
  Other: 'expenseCategory.other',
}

const accountNameKeys: Partial<Record<string, TranslationKey>> = {
  Cash: 'account.cash',
  'Bank BCA': 'account.bankBca',
  'Bank Mandiri': 'account.bankMandiri',
  Inventory: 'account.inventory',
  'Accounts Receivable': 'account.accountsReceivable',
  'Accounts Payable': 'account.accountsPayable',
  'Owner Equity': 'account.ownerEquity',
  'Sales Revenue': 'account.salesRevenue',
  'Cost of Goods Sold': 'account.costOfGoodsSold',
  'Replacement Cost': 'account.replacementCost',
  'Inventory Adjustment': 'account.inventoryAdjustment',
  'Delivery Transport': 'account.deliveryTransport',
}

export function translateExpenseCategory(name: string, t: (key: TranslationKey) => string) {
  const key = expenseCategoryKeys[name]
  return key ? t(key) : name
}

export function translateAccountName(name: string, t: (key: TranslationKey) => string) {
  const key = accountNameKeys[name]
  return key ? t(key) : translateExpenseCategory(name, t)
}
